function lookup(key: string, lang: Lang, vars?: Record<string, string | number>): string {
  const entry = DICT[key]
  let s = entry ? entry[lang] ?? entry.en : key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
  return s
}

interface Ctx {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: string, vars?: Record<string, string | number>) => string
}

const I18nCtx = createContext<Ctx | null>(null)

const SUPPORTED_LANGS: Lang[] = ['en', 'vi', 'it', 'zh', 'es', 'de', 'fr']

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('gs-lang') as Lang
    if (SUPPORTED_LANGS.includes(saved)) return saved
  } catch { /* ignore */ }

  if (typeof navigator !== 'undefined' && navigator.language) {
    const l = navigator.language.toLowerCase()
    for (const prefix of SUPPORTED_LANGS) {
      if (l.startsWith(prefix)) return prefix
    }
  }
  return 'en'
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLang] = useState<Lang>(initialLang)
  useEffect(() => {
    try {
      localStorage.setItem('gs-lang', lang)
    } catch { /* ignore */ }
  }, [lang])

  const value = useMemo<Ctx>(() => ({
    lang,
    setLang,
    t: (k, v) => lookup(k, lang, v),
  }), [lang])

  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>
}

export function useT(): Ctx {
  const ctx = useContext(I18nCtx)
  if (!ctx) throw new Error('useT must be inside I18nProvider')
  return ctx
}
